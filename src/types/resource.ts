export type ResourceCategory =
  | 'equipment'
  | 'room'
  | 'lab'
  | 'event_space'
  | 'facility';

export type ResourceStatus =
  | 'available'
  | 'in_use'
  | 'maintenance'
  | 'reserved'
  | 'restricted';

export interface ResourceRule {
  id: string;
  rule: string;
  isStrict: boolean;
}

export interface Resource {
  id: string;
  title: string;
  description: string;
  category: ResourceCategory;
  status: ResourceStatus;
  location: string;
  building?: string;
  roomNumber?: string;
  capacity?: number;
  ownerId: string;
  ownerName: string;
  ownerEmail?: string;
  imageUrl?: string;
  images?: string[];
  qrCodeData?: string; // QR code data payload or token for check-in
  qrCodeUrl?: string; // QR code image URL generated by backend (using qrcode lib)
  minTrustScore: number;
  hourlyRate?: number;
  securityDeposit?: number; // 0 for none, or deposit requirement
  isFree: boolean;
  ownerRole?: string;
  ownerDepartment?: string;
  ownerVerified?: boolean;
  availableDays?: string[];
  scheduleSlots?: Array<{ time: string; status: 'available' | 'booked' | 'contested' }>;
  specifications?: Record<string, string | number | boolean>;
  rules?: ResourceRule[];
  tags: string[];
  createdAt: string;
  updatedAt: string;
}

export interface ResourceFilterParams {
  category?: ResourceCategory | 'all';
  status?: ResourceStatus | 'all';
  search?: string;
  minTrustScore?: number;
  location?: string;
  page?: number;
  limit?: number;
}
